from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, ForeignKey, Index, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.config import get_settings


class Base(DeclarativeBase):
    pass


class Page(Base):
    __tablename__ = "pages"

    # MediaWiki's pageid, not our own sequence: it survives page renames, so re-ingesting a
    # renamed page updates the existing row instead of creating a duplicate.
    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=False)
    title: Mapped[str] = mapped_column(index=True)
    url: Mapped[str]
    # Compared with the wiki's latest revision to skip pages that haven't changed.
    revision_id: Mapped[int]
    # Vectors from different models can't be compared, so a model change forces re-embedding.
    embed_model: Mapped[str]
    ingested_at: Mapped[datetime] = mapped_column(server_default=func.now())

    chunks: Mapped[list["Chunk"]] = relationship(back_populates="page", passive_deletes=True)


class Chunk(Base):
    __tablename__ = "chunks"

    id: Mapped[int] = mapped_column(primary_key=True)
    page_id: Mapped[int] = mapped_column(ForeignKey("pages.id", ondelete="CASCADE"), index=True)
    position: Mapped[int]  # order within the page
    section: Mapped[str]  # heading path, e.g. "Abilities > Siphon Life"
    # What gets embedded, keyword-searched and shown to the LLM. Starts with a
    # "Page > Section" line so each chunk carries its own context.
    content: Mapped[str]
    embedding: Mapped[list[float]] = mapped_column(Vector(get_settings().embed_dimensions))
    # Generated by Postgres from content, so it can never drift out of sync.
    search_vector: Mapped[str] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', content)", persisted=True)
    )

    page: Mapped[Page] = relationship(back_populates="chunks")

    __table_args__ = (
        UniqueConstraint("page_id", "position"),
        # Approximate nearest-neighbour index for cosine distance (the <=> operator).
        Index(
            "ix_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
        # Full-text index for the keyword half of hybrid search.
        Index("ix_chunks_search_vector", "search_vector", postgresql_using="gin"),
    )
